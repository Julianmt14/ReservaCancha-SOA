-- DDL del Proveedor 1 · servicio-escenarios.
-- Hibernate solo valida estas tablas (spring.jpa.hibernate.ddl-auto: validate).

CREATE TABLE IF NOT EXISTS establecimientos (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre    VARCHAR(120) NOT NULL,
  direccion VARCHAR(200),
  ciudad    VARCHAR(80)  NOT NULL,
  telefono  VARCHAR(30),
  activo    BOOLEAN      NOT NULL DEFAULT TRUE,
  CONSTRAINT uk_establecimiento_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS canchas (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  establecimiento_id  BIGINT        NOT NULL,
  nombre              VARCHAR(120)  NOT NULL,
  deporte             VARCHAR(30)   NOT NULL,
  tipo                VARCHAR(60),
  superficie          VARCHAR(60),
  ubicacion           VARCHAR(120),
  precio_hora         DECIMAL(12,2) NOT NULL,
  duracion_minima_min INT           NOT NULL DEFAULT 60,
  horas_cancelacion   INT           NOT NULL DEFAULT 3,
  porcentaje_abono    INT           NOT NULL DEFAULT 50,
  activa              BOOLEAN       NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_cancha_establecimiento
    FOREIGN KEY (establecimiento_id) REFERENCES establecimientos (id),
  CONSTRAINT ck_cancha_precio      CHECK (precio_hora >= 0),
  CONSTRAINT ck_cancha_duracion    CHECK (duracion_minima_min > 0),
  CONSTRAINT ck_cancha_cancelacion CHECK (horas_cancelacion >= 0),
  CONSTRAINT ck_cancha_abono       CHECK (porcentaje_abono BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS horarios (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cancha_id     BIGINT      NOT NULL,
  dia_semana    VARCHAR(10) NOT NULL,
  hora_apertura TIME        NOT NULL,
  hora_cierre   TIME        NOT NULL,
  activo        BOOLEAN     NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_horario_cancha FOREIGN KEY (cancha_id) REFERENCES canchas (id),
  CONSTRAINT ck_horario_dia CHECK (dia_semana IN
    ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
  CONSTRAINT ck_horario_rango CHECK (hora_cierre > hora_apertura)
);
