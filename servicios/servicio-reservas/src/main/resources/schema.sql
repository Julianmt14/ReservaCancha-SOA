-- DDL del Proveedor 2 · servicio-reservas (H2 y PostgreSQL).
-- usuario_id y cancha_id son identificadores de otras aplicaciones (consumidora y Proveedor 1):
-- por eso NO tienen llave foránea; este servicio no lee las tablas de los demás.

CREATE TABLE IF NOT EXISTS reservas (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      BIGINT        NOT NULL,
  cancha_id       BIGINT        NOT NULL,
  fecha           DATE          NOT NULL,
  hora_inicio     TIME          NOT NULL,
  hora_fin        TIME          NOT NULL,
  valor_total     NUMERIC(12,2) NOT NULL,
  estado          VARCHAR(20)   NOT NULL,
  creado_en       TIMESTAMP WITH TIME ZONE NOT NULL,
  actualizado_en  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT ck_reserva_estado CHECK (estado IN ('PENDIENTE', 'PAGADA', 'CANCELADA')),
  CONSTRAINT ck_reserva_horas  CHECK (hora_fin > hora_inicio),
  CONSTRAINT ck_reserva_valor  CHECK (valor_total >= 0)
);

CREATE INDEX IF NOT EXISTS ix_reservas_usuario ON reservas (usuario_id);
CREATE INDEX IF NOT EXISTS ix_reservas_cancha_fecha ON reservas (cancha_id, fecha);

-- Mecanismo contra la doble reserva: cada reserva activa ocupa bloques de 30 minutos.
-- La restricción UNIQUE la hace cumplir la base de datos: si dos solicitudes simultáneas piden el
-- mismo bloque de la misma cancha, solo una inserción puede quedar; la otra recibe un error de
-- llave duplicada (el servicio responde 409). Al cancelar se borran los bloques y el horario queda libre.
CREATE TABLE IF NOT EXISTS bloques_reservados (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reserva_id   BIGINT NOT NULL,
  cancha_id    BIGINT NOT NULL,
  fecha        DATE   NOT NULL,
  hora_inicio  TIME   NOT NULL,
  CONSTRAINT fk_bloque_reserva FOREIGN KEY (reserva_id) REFERENCES reservas (id),
  CONSTRAINT uk_bloque UNIQUE (cancha_id, fecha, hora_inicio)
);

CREATE INDEX IF NOT EXISTS ix_bloques_reserva ON bloques_reservados (reserva_id);
